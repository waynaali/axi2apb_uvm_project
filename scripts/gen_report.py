#!/usr/bin/env python3
"""Summarise regression logs into docs/regression_summary.md.

Usage (from scripts/):  python3 gen_report.py [log_dir] [out_md]
Reads out/build/log_<test>_seed<N>.log written by `make run`. Nothing here is
hand-edited: every number comes from the simulator logs.
"""
import glob, os, re, sys

log_dir = sys.argv[1] if len(sys.argv) > 1 else "out/build"
out_md  = sys.argv[2] if len(sys.argv) > 2 else "../docs/regression_summary.md"

rows, cov_last = [], {}
for path in sorted(glob.glob(os.path.join(log_dir, "log_*_seed*.log"))):
    m = re.match(r"log_(.+)_seed(\d+)\.log", os.path.basename(path))
    if not m:
        continue
    test, seed = m.group(1), m.group(2)
    txt = open(path, errors="replace").read()
    sva_err = len(re.findall(r"^Error:", txt, re.M))     # SVA $error from simulator
    passed  = ("** TEST PASSED **" in txt) and sva_err == 0   # SVA failure fails the run
    sb      = re.search(r"SCOREBOARD SUMMARY: PASS=(\d+) FAIL=(\d+)", txt)
    uvm_err = re.search(r"UVM_ERROR\s*:\s*(\d+)", txt)
    uvm_fat = re.search(r"UVM_FATAL\s*:\s*(\d+)", txt)
    rows.append((test, seed, "PASS" if passed else "FAIL",
                 sb.group(1) if sb else "?", sb.group(2) if sb else "?",
                 uvm_err.group(1) if uvm_err else "?",
                 uvm_fat.group(1) if uvm_fat else "?", sva_err))
    for name, val in re.findall(r"(\w+_cg)\s*:\s*([\d.]+)%", txt):
        cov_last.setdefault(test, {})[name] = float(val)

lines = ["# Regression summary (generated by scripts/gen_report.py)", "",
         "| Test | Seed | Result | SB pass | SB fail | UVM_ERROR | UVM_FATAL | SVA errors |",
         "|---|---:|---|---:|---:|---:|---:|---:|"]
lines += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
n_pass = sum(1 for r in rows if r[2] == "PASS")
lines += ["", f"**{n_pass}/{len(rows)} runs passed.**", ""]
if cov_last:
    lines += ["## Functional coverage per test (instance, from [COV] report line)", "",
              "| Test | " + " | ".join(sorted({k for v in cov_last.values() for k in v})) + " |",
              "|---|" + "---:|" * len({k for v in cov_last.values() for k in v})]
    keys = sorted({k for v in cov_last.values() for k in v})
    for t, v in sorted(cov_last.items()):
        lines.append(f"| {t} | " + " | ".join(f"{v.get(k, 0):.1f}" for k in keys) + " |")
    lines += ["", "Merged coverage across all runs comes from URG: `make cov`.", ""]
failed = [r for r in rows if r[2] == "FAIL"]
if failed:
    lines += ["## Failures to classify (DUT / testbench / checker / sequence)", ""]
    lines += [f"- `{r[0]}` seed {r[1]}: log `{log_dir}/log_{r[0]}_seed{r[1]}.log`" for r in failed]
os.makedirs(os.path.dirname(out_md), exist_ok=True)
open(out_md, "w").write("\n".join(lines) + "\n")
print(f"wrote {out_md}: {n_pass}/{len(rows)} passed")
